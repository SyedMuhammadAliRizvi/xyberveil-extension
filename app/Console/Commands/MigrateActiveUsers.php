<?php

namespace App\Console\Commands;

use Illuminate\Console\Command;
use Illuminate\Support\Facades\DB;
use Illuminate\Support\Facades\Log;
use Illuminate\Support\Str;

class MigrateActiveUsers extends Command
{
    protected $signature = 'migrate:active-users {--dry : Run in dry mode without inserting records}';

    protected $description = 'Migrate all users and create subscriptions for those with valid (non-trial, ongoing) purchases.';

    protected $stats = [
        'total_users' => 0,
        'users_created' => 0,
        'users_skipped' => 0,
        'subscriptions_created' => 0,
        'errors' => 0,
    ];

    protected $legacyPlanId = null;

    public function handle()
    {
        $isDryRun = $this->option('dry');
        $startTime = microtime(true);

        $this->displayHeader($isDryRun);

        // Test old database connection
        try {
            DB::connection('old')->getPdo();
            $this->info('✅ Connected to old database successfully.');
        } catch (\Exception $e) {
            $this->error('❌ Could not connect to old database: '.$e->getMessage());

            return self::FAILURE;
        }

        // Count total users to migrate
        $this->stats['total_users'] = DB::connection('old')->table('users')->count();

        if ($this->stats['total_users'] === 0) {
            $this->warn('⚠️ No users found in old database.');

            return self::SUCCESS;
        }

        $this->info("📦 Found {$this->stats['total_users']} users to migrate.");
        $this->newLine();

        if (! $isDryRun && ! $this->confirm('Do you want to proceed with migration?', true)) {
            $this->info('Migration cancelled.');

            return self::SUCCESS;
        }

        // 🎯 Get or create single legacy plan
        if (! $isDryRun) {
            $this->legacyPlanId = $this->getOrCreateLegacyPlan();
            $this->info("📋 Using Legacy Plan (ID: {$this->legacyPlanId})");
            $this->newLine();
        }

        $bar = $this->output->createProgressBar($this->stats['total_users']);
        $bar->start();

        $chunkSize = 500;
        $errors = [];

        DB::connection('old')
            ->table('users')
            ->orderBy('id')
            ->chunk($chunkSize, function ($users) use ($bar, $isDryRun, &$errors) {
                foreach ($users as $oldUser) {
                    try {
                        // Check if user already exists
                        $userId = DB::table('users')->where('email', $oldUser->email)->value('id');

                        if ($userId) {
                            $this->stats['users_skipped']++;
                        } else {
                            // 👤 Create user with minimal data (FAST!)
                            if (! $isDryRun) {
                                // Generate unique app account token
                                $appAccountToken = $this->generateUniqueAppToken();

                                $userId = DB::table('users')->insertGetId([
                                    'name' => $oldUser->name,
                                    'email' => $oldUser->email,
                                    'slug' => null, // ✅ Will be generated by separate command
                                    'email_verified_at' => $oldUser->email_verified_at,
                                    'password' => $oldUser->password,
                                    'role' => $oldUser->role === 'admin' ? 'admin' : 'user',
                                    'registration_date' => $oldUser->registration_date ?? now(),
                                    'google_id' => $oldUser->google_id,
                                    'apple_id' => $oldUser->apple_id,
                                    'app_account_token' => $appAccountToken,
                                    'last_login' => $oldUser->last_login,
                                    'banned_at' => null,
                                    'ban_reason' => null,
                                    'created_at' => $oldUser->created_at ?? now(),
                                    'updated_at' => now(),
                                ]);

                                $this->stats['users_created']++;
                            } else {
                                $userId = null;
                            }
                        }

                        // 🧾 Get valid non-trial ongoing purchases
                        $purchases = DB::connection('old')
                            ->table('purchases')
                            ->where('purchases.user_id', $oldUser->id)
                            ->where('purchases.plan_id', '!=', 1) // exclude trial
                            ->where('purchases.status', 'active')
                            ->where('purchases.end_date', '>', now())
                            ->select(
                                'purchases.id as purchase_id',
                                'purchases.amount_paid',
                                'purchases.start_date',
                                'purchases.end_date',
                                'purchases.plan_id as old_plan_id',
                                'purchases.created_at',
                                'purchases.updated_at'
                            )
                            ->get();

                        // Process purchases if user has valid ones
                        if ($purchases->isNotEmpty() && ! $isDryRun) {
                            foreach ($purchases as $purchase) {
                                try {
                                    // 💳 Create subscription if not exists (all use same legacy plan)
                                    $exists = DB::table('local_subscriptions')
                                        ->where('user_id', $userId)
                                        ->where('plan_id', $this->legacyPlanId)
                                        ->where('starts_at', $purchase->start_date)
                                        ->where('ends_at', $purchase->end_date)
                                        ->exists();

                                    if (! $exists) {
                                        DB::table('local_subscriptions')->insert([
                                            'user_id' => $userId,
                                            'plan_id' => $this->legacyPlanId, // ✅ Single legacy plan for all
                                            'starts_at' => $purchase->start_date,
                                            'ends_at' => $purchase->end_date,
                                            'trial_ends_at' => null,
                                            'grace_ends_at' => null,
                                            'amount_paid' => $purchase->amount_paid ?? 0,
                                            'currency' => 'USD',
                                            'status' => 'active',
                                            'cancelled_by' => null,
                                            'cancelled_reason' => null,
                                            'is_recurring' => false,
                                            'provider' => 'local',
                                            'previous_subscription_id' => null,
                                            'proration_meta' => json_encode([
                                                'migrated_from_old_db' => true,
                                                'old_user_id' => $oldUser->id,
                                                'old_purchase_id' => $purchase->purchase_id,
                                                'old_plan_id' => $purchase->old_plan_id,
                                                'migration_date' => now()->toDateTimeString(),
                                                'migrated_by' => 'MianFarhan77',
                                            ]),
                                            'created_at' => $purchase->created_at ?? now(),
                                            'updated_at' => now(),
                                        ]);

                                        $this->stats['subscriptions_created']++;
                                    }
                                } catch (\Throwable $e) {
                                    $this->stats['errors']++;
                                    $errors[] = [
                                        'type' => 'purchase',
                                        'email' => $oldUser->email,
                                        'error' => $e->getMessage(),
                                    ];
                                    Log::error('Purchase migration error', [
                                        'user_id' => $oldUser->id,
                                        'email' => $oldUser->email,
                                        'purchase_id' => $purchase->purchase_id ?? null,
                                        'error' => $e->getMessage(),
                                    ]);
                                }
                            }
                        }

                        $bar->advance();
                    } catch (\Throwable $e) {
                        $this->stats['errors']++;
                        $errors[] = [
                            'type' => 'user',
                            'email' => $oldUser->email ?? 'unknown',
                            'error' => $e->getMessage(),
                        ];
                        Log::error('User migration error', [
                            'user_id' => $oldUser->id ?? null,
                            'error' => $e->getMessage(),
                        ]);
                        $bar->advance();
                    }
                }
            });

        $bar->finish();
        $this->newLine(2);

        $endTime = microtime(true);
        $executionTime = round($endTime - $startTime, 2);
        $memoryUsage = round(memory_get_peak_usage(true) / 1024 / 1024, 2);

        // Display summary
        $this->info('╔════════════════════════════════════════════╗');
        $this->info('║          Migration Summary                 ║');
        $this->info('╚════════════════════════════════════════════╝');
        $this->newLine();

        $this->table(
            ['Metric', 'Count'],
            [
                ['Total Users Found', $this->stats['total_users']],
                ['Users Created', $this->stats['users_created']],
                ['Users Skipped (Existed)', $this->stats['users_skipped']],
                ['Subscriptions Created', $this->stats['subscriptions_created']],
                ['Errors', $this->stats['errors']],
            ]
        );

        if (! empty($errors)) {
            $this->newLine();
            $this->error('❌ Errors encountered:');
            $this->table(
                ['Type', 'Email', 'Error'],
                array_map(fn ($e) => [$e['type'], $e['email'], Str::limit($e['error'], 60)], array_slice($errors, 0, 10))
            );

            if (count($errors) > 10) {
                $this->warn('... and '.(count($errors) - 10).' more errors. Check logs for details.');
            }
            $this->newLine();
            $this->info('💡 Full error details in: storage/logs/laravel.log');
        }

        $this->newLine();
        $this->info("⏱️  Execution time: {$executionTime} seconds");
        $this->info("💾 Peak memory usage: {$memoryUsage} MB");
        $this->newLine();

        if ($isDryRun) {
            $this->warn('🧪 DRY RUN COMPLETE — no changes were made.');
        } else {
            $this->info('✅ Migration complete!');
        }

        return self::SUCCESS;
    }

    /**
     * Get or create the single legacy plan for all migrated users
     */
    protected function getOrCreateLegacyPlan(): int
    {
        // Check if legacy plan already exists
        $legacyPlan = DB::table('plans')
            ->where('slug', 'legacy-migration-plan')
            ->first();

        if ($legacyPlan) {
            return $legacyPlan->id;
        }

        // Create the single legacy plan
        $planId = DB::table('plans')->insertGetId([
            'name' => 'Legacy Migration Plan',
            'slug' => 'legacy-migration-plan',
            'description' => 'Plan assigned to all users migrated from old database schema',
            'original_price' => 0.00,
            'discount_price' => 0.00,
            'currency' => 'USD',
            'is_active' => false, // Inactive - legacy plan
            'is_best_deal' => false,
            'trial_period' => 0,
            'trial_interval' => 'day',
            'invoice_period' => 1,
            'invoice_interval' => 'month',
            'grace_period' => 0,
            'grace_interval' => 'day',
            'created_at' => now(),
            'updated_at' => now(),
        ]);

        $this->info("✨ Created new legacy plan (ID: {$planId})");

        return $planId;
    }

    /**
     * Generate unique app_account_token (UUID format)
     */
    protected function generateUniqueAppToken(): string
    {
        do {
            $token = (string) Str::uuid();
        } while (DB::table('users')->where('app_account_token', $token)->exists());

        return $token;
    }

    protected function displayHeader(bool $isDryRun): void
    {
        $this->info('╔════════════════════════════════════════════╗');
        $this->info('║   Active Users Migration Tool              ║');
        $this->info('║   Old DB → New Schema                      ║');
        $this->info('╚════════════════════════════════════════════╝');
        $this->newLine();

        if ($isDryRun) {
            $this->warn('⚠️  DRY RUN MODE — no data will be inserted.');
        }

        $this->info('🔍 Starting user migration...');
        $this->newLine();
    }
}
